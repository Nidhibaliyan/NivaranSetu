export const VALID_LANGUAGE_CODES = new Set<LanguageCode>(
  Object.keys(LANGUAGE_METADATA) as LanguageCode[]
);

export function normalizeLanguageCode(code?: string | null): LanguageCode {
  if (typeof code !== 'string') return 'en';
  const normalized = code.trim().toLowerCase() as LanguageCode;
  return VALID_LANGUAGE_CODES.has(normalized) ? normalized : 'en';
}

export function getSpeechLocale(code?: string | null): string {
  return LANGUAGE_METADATA[normalizeLanguageCode(code)].speechLocale;
}

export function getLanguageMeta(code?: string | null): LanguageMetadata {
  return LANGUAGE_METADATA[normalizeLanguageCode(code)];
}

